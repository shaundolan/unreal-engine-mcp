"""Gameplay Ability System: gameplay tags, GameplayEffect / GameplayAbility Blueprints, granting abilities on
a character, and a generated C++ AttributeSet (AttributeSets cannot be Blueprints)."""

from __future__ import annotations

import re
from typing import Any

from . import call
from .blueprints import _LARGE, _finish
from .python_exec import run_editor_script

PY_OPS = {"create_effect", "set_effect", "create_ability", "set_ability", "inspect"}
TAG_FIELDS = (
    "asset_tags",
    "granted_tags",
    "ability_tags",
    "activation_owned_tags",
    "activation_required_tags",
    "activation_blocked_tags",
    "cancel_abilities_with_tag",
    "block_abilities_with_tag",
)
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def class_path(asset: str) -> str:
    """/Game/X/GA_Heal -> /Game/X/GA_Heal.GA_Heal_C (Blueprint generated class)."""
    if asset.endswith("_C") or asset.startswith("/Script/"):
        return asset
    pkg = asset.split(".")[0]
    name = pkg.rsplit("/", 1)[-1]
    return f"{pkg}.{name}_C"


def attribute_set_source(
    name: str, module: str, attributes: list[str], defaults: dict[str, float] | None = None, replicated: bool = True
) -> dict[str, str]:
    """Header + source text for a UAttributeSet with ATTRIBUTE_ACCESSORS, replication and Max* clamping."""
    if (
        not _IDENT.match(name)
        or not _IDENT.match(module)
        or not attributes
        or not all(_IDENT.match(a) for a in attributes)
    ):
        raise ValueError("name, module and attributes must be C++ identifiers (and at least one attribute)")
    cls = name if (len(name) > 1 and name[0] == "U" and name[1].isupper()) else f"U{name}"
    stem = cls[1:]
    api = f"{module.upper()}_API"
    defaults = defaults or {}
    clamp = [a for a in attributes if f"Max{a}" in attributes]
    decls, reps, onreps, inits = [], [], [], []
    for a in attributes:
        rep = f", ReplicatedUsing = OnRep_{a}" if replicated else ""
        decls.append(
            f'\tUPROPERTY(BlueprintReadOnly, Category = "Attributes"{rep})\n'
            f"\tFGameplayAttributeData {a};\n\tATTRIBUTE_ACCESSORS({cls}, {a})\n"
        )
        if replicated:
            reps.append(f"\tDOREPLIFETIME_CONDITION_NOTIFY({cls}, {a}, COND_None, REPNOTIFY_Always);")
            onreps.append(
                f"void {cls}::OnRep_{a}(const FGameplayAttributeData& Old{a})\n"
                f"{{\n\tGAMEPLAYATTRIBUTE_REPNOTIFY({cls}, {a}, Old{a});\n}}\n"
            )
        if a in defaults:
            inits.append(f"\tInit{a}({float(defaults[a])}f);")
    onrep_decls = "".join(
        f"\tUFUNCTION()\n\tvoid OnRep_{a}(const FGameplayAttributeData& Old{a});\n" for a in attributes
    )
    clamp_pre = "".join(
        f"\tif (Attribute == Get{a}Attribute())\n\t{{\n"
        f"\t\tNewValue = FMath::Clamp(NewValue, 0.f, GetMax{a}());\n\t}}\n"
        for a in clamp
    )
    clamp_post = "".join(
        f"\tif (Data.EvaluatedData.Attribute == Get{a}Attribute())\n\t{{\n"
        f"\t\tSet{a}(FMath::Clamp(Get{a}(), 0.f, GetMax{a}()));\n\t}}\n"
        for a in clamp
    )
    rep_decl = (
        "\tvirtual void GetLifetimeReplicatedProps(TArray<FLifetimeProperty>& OutLifetimeProps) const override;"
        if replicated
        else ""
    )
    header = f"""// Generated by UnrealMCP gas_edit (attribute_set). Edit freely.
#pragma once

#include "CoreMinimal.h"
#include "AttributeSet.h"
#include "AbilitySystemComponent.h"
#include "{stem}.generated.h"

#ifndef ATTRIBUTE_ACCESSORS
#define ATTRIBUTE_ACCESSORS(ClassName, PropertyName) \\
	GAMEPLAYATTRIBUTE_PROPERTY_GETTER(ClassName, PropertyName) \\
	GAMEPLAYATTRIBUTE_VALUE_GETTER(PropertyName) \\
	GAMEPLAYATTRIBUTE_VALUE_SETTER(PropertyName) \\
	GAMEPLAYATTRIBUTE_VALUE_INITTER(PropertyName)
#endif

UCLASS()
class {api} {cls} : public UAttributeSet
{{
	GENERATED_BODY()

public:
	{cls}();

{chr(10).join(decls)}
	virtual void PreAttributeChange(const FGameplayAttribute& Attribute, float& NewValue) override;
	virtual void PostGameplayEffectExecute(const struct FGameplayEffectModCallbackData& Data) override;
{rep_decl}

protected:
{onrep_decls if replicated else ""}}};
"""
    source = f"""// Generated by UnrealMCP gas_edit (attribute_set). Edit freely.
#include "{stem}.h"
#include "GameplayEffectExtension.h"
#include "Net/UnrealNetwork.h"

{cls}::{cls}()
{{
{chr(10).join(inits)}
}}

void {cls}::PreAttributeChange(const FGameplayAttribute& Attribute, float& NewValue)
{{
	Super::PreAttributeChange(Attribute, NewValue);
{clamp_pre}}}

void {cls}::PostGameplayEffectExecute(const FGameplayEffectModCallbackData& Data)
{{
	Super::PostGameplayEffectExecute(Data);
{clamp_post}}}
"""
    if replicated:
        source += f"""
void {cls}::GetLifetimeReplicatedProps(TArray<FLifetimeProperty>& OutLifetimeProps) const
{{
	Super::GetLifetimeReplicatedProps(OutLifetimeProps);
{chr(10).join(reps)}
}}

{chr(10).join(onreps)}"""
    return {
        "class": cls,
        "header_name": f"{stem}.h",
        "source_name": f"{stem}.cpp",
        "header": header,
        "source": source,
        "attribute_path": f"/Script/{module}.{stem}",
    }


GAS_DEPS = ("GameplayAbilities", "GameplayTags", "GameplayTasks")


def add_build_deps(build_cs: str, deps=GAS_DEPS) -> str:
    """Insert missing module names into PublicDependencyModuleNames.AddRange(new string[] { ... })."""
    missing = [d for d in deps if f'"{d}"' not in build_cs]
    if not missing:
        return build_cs
    m = re.search(r"PublicDependencyModuleNames\.AddRange\(\s*new\s+string\[\]\s*\{", build_cs)
    if not m:
        raise ValueError("Build.cs has no PublicDependencyModuleNames.AddRange(new string[] { ... })")
    insert = " " + ", ".join(f'"{d}"' for d in missing) + ","
    return build_cs[: m.end()] + insert + build_cs[m.end() :]


def tag_names(value: Any) -> list[str]:
    """Tag names inside a property_get JSON value (FInheritedTagContainer / FGameplayTagContainer)."""
    if isinstance(value, str):
        return re.findall(r'TagName="([^"]+)"', value)
    found: list[str] = []

    def walk(v: Any, key: str = "") -> None:
        if isinstance(v, dict):
            if key in ("removed", "Removed"):
                return
            for k, x in v.items():
                if k.lower() == "tagname" and isinstance(x, str):
                    found.append(x)
                else:
                    walk(x, k)
        elif isinstance(v, list):
            for x in v:
                walk(x, key)

    walk(value.get("Added", value.get("added", value)) if isinstance(value, dict) else value)
    return list(dict.fromkeys(found))


def register(mcp, get_conn):
    def tags_in(ops: list[dict[str, Any]]) -> list[str]:
        seen: list[str] = []
        for op in ops:
            for f in TAG_FIELDS:
                for t in op.get(f) or []:
                    if t not in seen:
                        seen.append(t)
        return seen

    def script_op(body: dict[str, Any]) -> dict[str, Any]:
        """One gas_edit editor-script op -> flat {success, ...}; GE tag components read via property_get."""
        r = run_editor_script(get_conn, "gas_edit", {"operations": [body]}, timeout_s=300)
        if not r.get("success"):
            return r
        res = (r.get("results") or [{}])[0]
        out = {"success": bool(res.pop("ok", False)), **{k: v for k, v in res.items() if k not in ("index", "op")}}
        for c in out.pop("tag_components", None) or []:
            g = call(get_conn, "property_get", {"path": c["path"], "property": c["property"]})
            out[c["field"]] = tag_names(g.get("value"))
        return out

    def finish_tags(asset: str, r: dict[str, Any]) -> dict[str, Any]:
        """Set GE tag-component properties (not reachable from Python) with C++ property_set, then compile+save."""
        created = r.get("created")
        for p in r.get("pending", []):
            s = call(get_conn, "property_set", {"path": p["path"], "property": p["property"], "value": p["value"]})
            if not s.get("success"):
                return {"success": False, "error": f"{p['property']}: {s.get('error')}", "created": created}
        out = script_op({"op": "finalize", "asset": asset})
        out["created"] = created
        return out

    def grant(op: dict[str, Any]) -> dict[str, Any]:
        character = op.get("character", "")
        abilities = op.get("abilities") or []
        comp = op.get("component") or "AbilitySystem"
        spec = call(get_conn, "bp_export", {"blueprint": character, "graphs": ["EventGraph"], "include_pins": True})
        if not spec.get("success"):
            return spec
        ops: list[dict[str, Any]] = []
        existing = next(
            (c["name"] for c in spec.get("components", []) if c.get("class") == "AbilitySystemComponent"), None
        )
        if existing:
            comp = existing
        elif op.get("inherited_component"):
            comp = op["inherited_component"]
        else:
            props: dict[str, Any] = {}
            if op.get("attribute_sets"):
                props["DefaultStartingData"] = [
                    {"Attributes": a if a.startswith("/") else f"/Script/GameplayAbilities.{a}"}
                    for a in op["attribute_sets"]
                ]
            ops.append({"op": "add_component", "name": comp, "class": "AbilitySystemComponent", "properties": props})
        begin_links: list[str] = []
        for g in spec.get("graphs", []):
            for n in g.get("nodes", []):
                if n.get("kind") == "event" and n.get("event") in ("ReceiveBeginPlay", "BeginPlay"):
                    for p in n.get("pins", []):
                        if p.get("name") == "then":
                            begin_links = p.get("links", [])
        ops += [
            {"op": "add_node", "id": "mcp_begin", "kind": "event", "event": "BeginPlay"},
            {"op": "add_node", "id": "mcp_asc", "kind": "get_var", "variable": comp},
        ]
        prev = "mcp_begin.then"
        for i, a in enumerate(abilities):
            nid = f"mcp_give{i}"
            ops += [
                {
                    "op": "add_node",
                    "id": nid,
                    "kind": "call_function",
                    "function": "GiveAbility",
                    "class": "AbilitySystemComponent",
                    "pins": {"AbilityClass": class_path(a), "Level": int(op.get("level", 1))},
                },
                {"op": "connect", "from": prev, "to": f"{nid}.exec"},
                {"op": "connect", "from": "mcp_asc." + comp, "to": f"{nid}.self"},
            ]
            prev = f"{nid}.then"
        if begin_links and abilities:  # keep what BeginPlay already did: run it after the grants
            ops.append({"op": "connect", "from": prev, "to": begin_links[0]})
        r = _finish(
            call(
                get_conn,
                "bp_apply",
                {
                    "blueprint": character,
                    "operations": ops,
                    "create_parent": "",
                    "compile": True,
                    "atomic": True,
                    "dry_run": False,
                    "save": True,
                },
                timeout=_LARGE,
            )
        )
        r["component"] = comp
        r["granted"] = [class_path(a) for a in abilities]
        return r

    def attribute_set(op: dict[str, Any]) -> dict[str, Any]:
        module = op.get("module") or ""
        gen = attribute_set_source(
            op.get("name") or "",
            module,
            op.get("attributes") or [],
            op.get("defaults"),
            bool(op.get("replicated", True)),
        )
        out: dict[str, Any] = {"success": True, **gen, "written": []}
        if not op.get("write"):
            out["next"] = (
                "write=true puts these in Source/<module>/ (Public/Private when the module has them) and adds "
                f"{', '.join(GAS_DEPS)} to the module's Build.cs; then rebuild and restart the editor."
            )
            return out
        listing = run_editor_script(get_conn, "cpp_source", {"action": "list", "pattern": f"Source/{module}/*"})
        if not listing.get("success"):
            return listing
        files = listing.get("files", [])
        build = f"Source/{module}/{module}.Build.cs"
        if build not in files:
            return {"success": False, "error": f"{build} not found: module must be one of the project's C++ modules"}
        split = any(f.startswith(f"Source/{module}/Public/") for f in files)
        h = f"Source/{module}/{'Public/' if split else ''}{gen['header_name']}"
        c = f"Source/{module}/{'Private/' if split else ''}{gen['source_name']}"
        for path, text in ((h, gen["header"]), (c, gen["source"])):
            w = run_editor_script(get_conn, "cpp_source", {"action": "write", "path": path, "content": text})
            if not w.get("success"):
                return w
            out["written"].append(path)
        cs = run_editor_script(get_conn, "cpp_source", {"action": "read", "path": build})
        if not cs.get("success"):
            return cs
        patched = add_build_deps(cs["content"])
        if patched != cs["content"]:
            w = run_editor_script(get_conn, "cpp_source", {"action": "write", "path": build, "content": patched})
            if not w.get("success"):
                return w
            out["written"].append(build)
        out["next"] = (
            "New UCLASS: close the editor, build the project (Linux: scripts/ue_linux.sh build; Windows: "
            "Build.bat or the IDE), relaunch. Live Coding cannot add classes. Then use "
            f"'{gen['class'][1:]}.<Attribute>' in create_effect modifiers."
        )
        return out

    @mcp.tool()
    def gameplay_tags(
        action: str = "list", tags: list[str] | None = None, prefix: str = "", comment: str = ""
    ) -> dict[str, Any]:
        """List the project's gameplay tags (prefix filters, e.g. "Ability.") or add tags (action="add",
        tags=["Ability.Heal","Effect.Heal"]) to Config/DefaultGameplayTags.ini; they are usable immediately.
        Returns tags, added, already_existed, errors."""
        r = call(
            get_conn, "gameplay_tags", {"action": action, "tags": tags or [], "prefix": prefix, "comment": comment}
        )
        if r.get("success") and "ok" in r:
            r["success"] = bool(r.pop("ok"))
            if not r["success"]:
                r["error"] = "; ".join(r.get("errors", []))
        return r

    @mcp.tool()
    def gas_edit(operations: list[dict[str, Any]]) -> dict[str, Any]:
        """Gameplay Ability System authoring (GameplayAbilities plugin). Ops run in order:
          {"op":"create_effect","asset":"/Game/GAS/GE_Heal","duration":"instant",
           "modifiers":[{"attribute":"AbilitySystemTestAttributeSet.Health","op":"add","magnitude":25}],
           "asset_tags":["Effect.Heal"]}
              duration: "instant" | "infinite" | seconds; "period": seconds (periodic, e.g. heal over time);
              modifier op: add | multiply | divide | override | add_final | multiply_compound;
              magnitude: number or {"set_by_caller":"Data.Amount"}; "granted_tags": tags the target has while
              active; "stack_limit": n; "properties": other class defaults (C++ names)
          {"op":"set_effect","asset":...,...}                     same fields on an existing effect
          {"op":"create_ability","asset":"/Game/GAS/GA_Heal","ability_tags":["Ability.Heal"],
           "activation_owned_tags":[...],"cancel_abilities_with_tag":[...],"block_abilities_with_tag":[...],
           "activation_required_tags":[...],"activation_blocked_tags":[...],"cost_effect":"/Game/GAS/GE_Cost",
           "cooldown_effect":"/Game/GAS/GE_Cooldown","instancing":"instanced_per_actor","parent":"GameplayAbility",
           "graph":[bp_apply ops]}   e.g. event ActivateAbility -> ApplyGameplayEffectToOwner -> EndAbility
          {"op":"set_ability","asset":...,...}
          {"op":"grant_abilities","character":"/Game/BP_Hero","abilities":["/Game/GAS/GA_Heal"],
           "attribute_sets":["AbilitySystemTestAttributeSet"],"level":1}
              adds an AbilitySystemComponent (named "AbilitySystem", unless one exists) with those attribute
              sets, and gives the abilities on BeginPlay (before whatever BeginPlay already did)
          {"op":"attribute_set","module":"MyGame","name":"HealthSet","attributes":["Health","MaxHealth"],
           "defaults":{"Health":100,"MaxHealth":100},"write":true}
              generates a C++ UAttributeSet (accessors, replication, Health clamped to MaxHealth); write=true saves
              it into the module and adds GameplayAbilities/GameplayTags/GameplayTasks to its Build.cs. Rebuild +
              restart, then use "HealthSet.Health". Without C++, the engine's AbilitySystemTestAttributeSet
              (Health, MaxHealth, Mana, Damage, ...) works for prototypes.
          {"op":"inspect","asset":...}                            read an effect/ability back
        Tags named in any op are added to the tag table first. Returns success and results per op."""
        results: list[dict[str, Any]] = []
        tags = tags_in(operations)
        if tags:
            t = call(get_conn, "gameplay_tags", {"action": "add", "tags": tags})
            if not t.get("success") or t.get("errors"):
                return {
                    "success": False,
                    "error": f"could not register tags {tags}: {t.get('error') or '; '.join(t.get('errors', []))}",
                }
        for i, op in enumerate(operations):
            kind = op.get("op")
            rec: dict[str, Any] = {"index": i, "op": kind}
            if kind in PY_OPS:
                body = {k: v for k, v in op.items() if k != "graph"}
                r = script_op(body)
                if r.get("success") and r.get("pending"):
                    r = finish_tags(op["asset"], r)
                if r.get("success") and op.get("graph"):
                    g = _finish(
                        call(
                            get_conn,
                            "bp_apply",
                            {
                                "blueprint": op["asset"],
                                "operations": op["graph"],
                                "create_parent": "",
                                "compile": True,
                                "atomic": True,
                                "dry_run": False,
                                "save": True,
                            },
                            timeout=_LARGE,
                        )
                    )
                    r["graph"] = g
                    if not g.get("success"):
                        r.update(success=False, error=f"graph: {g.get('error')}")
            elif kind == "grant_abilities":
                r = grant(op)
            elif kind == "attribute_set":
                try:
                    r = attribute_set(op)
                except ValueError as e:
                    r = {"success": False, "error": str(e)}
            else:
                r = {"success": False, "error": f"unknown op {kind!r}"}
            rec["ok"] = bool(r.pop("success", False))
            rec.update(r)
            results.append(rec)
        failed = [x for x in results if not x.get("ok")]
        out: dict[str, Any] = {"success": not failed, "results": results}
        if tags:
            out["tags_registered"] = tags
        if failed:
            out["error"] = "; ".join(f"op {x['index']} ({x['op']}): {str(x.get('error'))[-300:]}" for x in failed[:6])
        return out

    @mcp.tool()
    def gas_inspect(asset: str) -> dict[str, Any]:
        """Read a GameplayEffect Blueprint (duration_policy, duration, period, modifiers [attribute, op,
        magnitude], asset_tags, granted_tags) or a GameplayAbility Blueprint (tags, cost/cooldown effects,
        instancing)."""
        return script_op({"op": "inspect", "asset": asset})
